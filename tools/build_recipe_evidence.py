#!/usr/bin/env python3
"""Check/generate the independent recipe supplement without changing frozen data.

The checked-in excerpt/provenance registry is the input. Skill minima must come
from an exact spell/output/profession join, never difficulty colors or source
cardinality. Acquisition methods remain independent and additive.
"""
import argparse
import json
import html
import re
from pathlib import Path
from build_acquisition_navigation import lua, PROFESSION_SKILLS
from research_sources import require_evidence_tree
from build_catalogue_verification import render_recipe_corrections

ROOT=Path(__file__).resolve().parents[1]
D=ROOT/'docs/recipe-audit'
MARKER='-- BEGIN GENERATED RECIPE EVIDENCE\n'


def book_requirements(tooltip, profession):
    # The book tooltip embeds a complete finished-item tooltip after its Use.
    # Neither wearer level nor the embedded reagent list is a learning gate.
    prefix=tooltip.split('Use:',1)[0]
    text=html.unescape(re.sub('<[^>]+>',' ',re.sub(r'<br\s*/?>','\n',prefix)))
    result=[]
    for line in text.splitlines():
        line=' '.join(line.split())
        if line.startswith('Requires ') and not re.fullmatch('Requires '+re.escape(profession)+r' \(\d+\)',line):
            result.append(line)
    return result


def render():
    evidence=json.loads((D/'evidence.json').read_text())
    pages=json.loads((D/'fresh-spell-pages.json').read_text())
    records=evidence['records']
    require_evidence_tree(records)
    books=json.loads((D/'fresh-book-pages.json').read_text())
    for key,record in records.items():
        assert str(record['itemID'])==key and record['profession'] in PROFESSION_SKILLS
        page=pages[str(record['spellID'])]
        exact=[r for r in page['lists'].get('recipes',[]) if r.get('id')==record['spellID']
               and r.get('name')==record['name'] and (r.get('creates')or[None])[0]==record['itemID']
               and PROFESSION_SKILLS[record['profession']] in r.get('skill',[])
               and r.get('envChange',{}).get('status')!='unconfirmed']
        assert len(exact)==1 and exact[0]['learnedat']==record['craftingSkill']
        assert type(record['craftingSkill'])is int and 0<record['craftingSkill']<1000
        assert page['sha256']==record['evidence'][0]['sha256']
        requirements=[]
        for book in record['books']:
            page=books[str(book['itemID'])]
            assert page['sha256']==book['evidence']['sha256']
            requirements.extend(book_requirements(json.loads(page['tooltip']),record['profession']))
            assert any(r.get('id')==record['spellID'] and r.get('name')==record['name']
                       and (r.get('creates')or[None])[0]==record['itemID']
                       for r in page['lists'].get('teaches-recipe',[]))
        assert sorted(set(requirements))==record.get('learningRequirements',[])
        for drop in record['documentedDrops']:
            page=books[str(drop['bookItemID'])]
            assert page['sha256']==drop['evidence'][0]['sha256']
            assert any(r.get('id')==drop['npcID'] and r.get('name')==drop['name']
                       for r in page['lists'].get('dropped-by',[]))
        for route in record['acquisitions']:
            assert route['verification']=='published-reference' and route['evidence']
            assert not any(k in route for k in ['x','y','bounds','dropRate','boss'])
    text=MARKER+'-- Generated by tools/build_recipe_evidence.py; source fingerprints in docs/recipe-audit.\n'+\
        'GetGear.RecipeEvidence={\n'+',\n'.join('['+k+']='+lua(v) for k,v in sorted(records.items(),key=lambda x:int(x[0])))+'\n}\n'+'''
-- Add only documented alternatives. Keep old methods, restrictions and source
-- geography; a new recipe fact cannot replace materials or equipment identity.
for id,record in pairs(GetGear.RecipeEvidence) do
    local gear=GetGear.ItemCatalog and GetGear.ItemCatalog[id]
    local model=GetGear.AcquisitionNavigationData
    if gear and model and gear.name==record.name and gear.profession==record.profession then
        if #record.books==1 and not gear.recipePatternItemID then
            gear.recipePatternItemID=record.books[1].itemID
            if not gear.recipeLearnMethod or gear.recipeLearnMethod=="unverified" then gear.recipeLearnMethod="pattern" end
        end
        local plan=model.items[tostring(id)] or {itemID=id,category="crafting",routes={}}
        model.items[tostring(id)]=plan
        for _,route in ipairs(record.acquisitions) do
            local duplicate=false
            for _,old in ipairs(plan.routes) do
                if old.kind==route.kind and old.source==route.source and old.dungeon==route.dungeon
                    and (route.source or old.enemyName==route.enemyName and old.bookItemID==route.bookItemID) then duplicate=true;break end
            end
            if not duplicate then
                if route.source and not model.sources[route.source] then
                    model.sources[route.source]={name=route.actorName,locations={},evidence=route.evidence}
                end
                plan.routes[#plan.routes+1]=route
            end
        end
    end
end
'''
    return text+render_recipe_corrections()


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    path=ROOT/'RecipeKnowledge.lua';old=path.read_text();prefix=old.split(MARKER)[0]
    expected=prefix+render()
    if a.check:assert old==expected,'Recipe evidence is stale'
    else:path.write_text(expected)
    print('PASS independent recipe supplement: exact profession/output/minimum joins, additive sources, no guessed coordinates/rates')

if __name__=='__main__':main()
