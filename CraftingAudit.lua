local applied, preserved = {}, {}
for id, recipe in pairs(recipes) do
    local item=catalog[id]
    assert(item, "CraftingAudit: missing item "..id)
    if type(item.reagents)=="table" and #item.reagents>0 then
        preserved[#preserved+1]=id
    else
        item.reagents={}
        for _,ingredient in ipairs(recipe) do
            local matID, count=ingredient[1], ingredient[2]
            item.reagents[#item.reagents+1]={
                itemID=matID, amount=count, name=assert(names[matID], "Unknown ingredient "..matID),
            }
        end
        applied[#applied+1]=id
    end
end
